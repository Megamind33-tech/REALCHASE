import { chromium } from 'playwright';
import { setTimeout as sleep } from 'node:timers/promises';
import fs from 'node:fs';
const url = process.env.URL || 'http://localhost:4177';
const out = 'docs/evidence/phase-2/keying-realism';
fs.mkdirSync(out, { recursive: true });
const args = ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--no-sandbox','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream'];
const browser = await chromium.launch({ headless: true, executablePath: process.env.PW_EXECUTABLE, args });
const ctx = await browser.newContext({ viewport: { width: 1600, height: 900 } });
await ctx.grantPermissions(['camera','microphone'], { origin: url });
const page = await ctx.newPage();
const logs=[]; page.on('console',m=>logs.push(`[${m.type()}] ${m.text()}`)); page.on('pageerror',e=>logs.push(`[err] ${e.message}`));
const vp = async (n) => { const e = await page.$('#babylon-viewport'); if (e) await e.screenshot({ path: `${out}/${n}` }); };
const setSelect = (v) => page.evaluate((val)=>{const s=[...document.querySelectorAll('select')].find(x=>[...x.options].some(o=>o.value===val&&!o.disabled)); if(s){s.value=val; s.dispatchEvent(new Event('change',{bubbles:true}));}}, v);
const setRange = (label,v) => page.evaluate(({label,v})=>{const r=[...document.querySelectorAll('input[type=range]')].find(x=>x.getAttribute('aria-label')===label); if(r){const set=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set; set.call(r,String(v)); r.dispatchEvent(new Event('input',{bubbles:true})); r.dispatchEvent(new Event('change',{bubbles:true}));}}, {label,v});
await page.goto(url,{waitUntil:'load'}); await page.waitForSelector('#chase-babylon-canvas'); await sleep(2200);
await page.click('button[title="Switcher"]'); await sleep(400);
await page.getByRole('button',{name:'Add Webcam'}).click(); await page.waitForSelector('video'); await sleep(1200);
await page.getByRole('button',{name:'CUT'}).click(); await sleep(800);
await setSelect('presenterPlate'); await sleep(300); await setSelect('chromaKey'); await sleep(400);
// Auto-sample the key color from the live backdrop, then a small tune
await page.getByRole('button',{name:'Auto'}).click(); await sleep(300);
const keyColor = await page.evaluate(()=>{const i=document.querySelector('input[aria-label="Key color"]'); return i ? i.value : null;});
await setRange('Similarity', 0.18); await setRange('Smoothness', 0.12); await setRange('Spill', 0.8); await sleep(300);
await page.screenshot({ path: `${out}/01-realism-controls-auto.png` });
await page.click('button[title="Builder"]'); await page.waitForSelector('#chase-babylon-canvas'); await sleep(3500);
await vp('02-chromakey-realism-result.png');
await page.click('button[title="Switcher"]'); await sleep(300);
await page.getByRole('button',{name:'Show matte'}).click(); await sleep(300);
await page.click('button[title="Builder"]'); await page.waitForSelector('#chase-babylon-canvas'); await sleep(3000);
await vp('03-realism-matte.png');
fs.writeFileSync(`${out}/keying-realism.txt`, [`auto-sampled key color: ${keyColor}`, '', '--- console ---', ...logs].join('\n'));
await browser.close();
console.log('auto key color:', keyColor, '-> evidence', out);
